#!/usr/bin/env python3
"""Extract Inter 600 glyph metrics into inter-600-glyphs.ts for seat-label placement."""

from __future__ import annotations

import importlib.metadata
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

SCRIPT_DIR = Path(__file__).resolve().parent
WEB_ROOT = SCRIPT_DIR.parent
FONT_PATH = WEB_ROOT / "public/fonts/inter/InterVariable.woff2"
OUT_PATH = WEB_ROOT / "src/app/shared/map/inter-600-glyphs.ts"

# Space, punctuation, digits, Latin and Polish letters used in seat/district labels.
CHARS = (
    " "
    "-()."
    "0123456789"
    "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
    "abcdefghijklmnopqrstuvwxyz"
    "ĄĆĘŁŃÓŚŹŻ"
    "ąćęłńóśźż"
)


def ts_key(ch: str) -> str:
    if ch == "'":
        return "\"'\""
    return repr(ch)


def main() -> None:
    fonttools_version = importlib.metadata.version("fonttools")

    font = TTFont(str(FONT_PATH))
    instantiateVariableFont(font, {"wght": 600}, inplace=True)
    units = font["head"].unitsPerEm
    if units != 2048:
        raise SystemExit(f"unitsPerEm={units}, expected 2048")

    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()
    glyphs: dict[str, dict[str, int]] = {}
    missing: list[str] = []
    for ch in CHARS:
        name = cmap.get(ord(ch))
        if name is None:
            missing.append(ch)
            continue
        g = glyph_set[name]
        pen = BoundsPen(glyph_set)
        g.draw(pen)
        bounds = pen.bounds
        if bounds is None:
            y_min, y_max = 0, 0
        else:
            y_min, y_max = int(bounds[1]), int(bounds[3])
        glyphs[ch] = {"advance": int(g.width), "yMin": y_min, "yMax": y_max}

    if missing:
        raise SystemExit(f"missing glyphs for {missing!r}")

    how_to_run = (
        "python3 -m venv /tmp/pr159-venv && "
        "/tmp/pr159-venv/bin/pip install fonttools brotli && "
        "/tmp/pr159-venv/bin/python apps/web/scripts/extract-inter-glyphs.py"
    )
    lines = [
        "/**",
        " * Generated by apps/web/scripts/extract-inter-glyphs.py — do not edit by hand.",
        f" * Run: {how_to_run}",
        f" * fontTools {fonttools_version}; InterVariable.woff2 at wght 600; unitsPerEm 2048.",
        " */",
        "export const INTER_600_GLYPHS: Readonly<",
        "  Record<",
        "    string,",
        "    { readonly advance: number; readonly yMin: number; readonly yMax: number }",
        "  >",
        "> = {",
    ]
    for ch in CHARS:
        g = glyphs[ch]
        lines.append(
            f"  {ts_key(ch)}: {{"
            f" advance: {g['advance']},"
            f" yMin: {g['yMin']},"
            f" yMax: {g['yMax']} }},"
        )
    lines.append("};")
    lines.append("")

    OUT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT_PATH} ({len(glyphs)} glyphs, fontTools {fonttools_version})")


if __name__ == "__main__":
    main()
